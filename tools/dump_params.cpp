// Writes the parameter reference (reStructuredText) from the parameter table.
//   dump_params > Documentation/parameters.rst
// The "params-doc" CTest regenerates it and fails when the committed file is stale.
#include "../src/common/Params.hpp"

#include <cstdio>
#include <string>
#include <vector>

using namespace lstrip;

static std::string num(float v) {
    char b[32];
    if (v == static_cast<int>(v)) std::snprintf(b, sizeof b, "%d", static_cast<int>(v));
    else std::snprintf(b, sizeof b, "%g", v);
    return b;
}
static void emit(std::string s) {   // no trailing whitespace in generated docs
    while (!s.empty() && s.back() == ' ') s.pop_back();
    std::puts(s.c_str());
}
static const char* unitName(Unit u) {
    switch (u) {
    case Unit::dB: return "dB"; case Unit::Percent: return "%"; case Unit::Hz: return "Hz";
    case Unit::kHz: return "Hz"; case Unit::ms: return "ms"; case Unit::Midi: return "MIDI";
    default: return "";
    }
}
static const char* group(uint32_t id) {
    if (id <= kGateThresh) return "Master";
    if (id <= kDeessListen) return "Dynamics";
    if (id <= kChorusVoices) return "Space";
    if (id <= kMbHigh) return "Multiband";
    if (id <= kEqLowCut) return "Equalizer";
    if (id <= kTuneMix) return "Auto-tune";
    return "Outputs";
}

int main() {
    std::puts(".. This file is generated by tools/dump_params.cpp from");
    std::puts("   src/common/Params.hpp.  Do not edit it by hand; run:");
    std::puts("       cmake --build build --target params-doc");
    std::puts("");
    std::puts("====================");
    std::puts("Parameter reference");
    std::puts("====================");
    std::puts("");
    std::puts("Every control in L-STRIP is one of the parameters below.  The *symbol* is");
    std::puts("the stable identifier used in preset files; the *id* is the position in the");
    std::puts("host's parameter list.  Ids and symbols never change once released: new");
    std::printf("parameters are only ever appended.  Parameters with id >= %u are read-only\n", kNumInputParams);
    std::puts("meters for the editor; they are hidden from hosts.");
    std::puts("");

    const char* cur = "";
    std::vector<uint32_t> enums;
    for (uint32_t i = 0; i < kParamCount; ++i) {
        const char* g = group(i);
        if (std::string(g) != cur) {
            cur = g;
            std::puts(""); std::puts(g);
            std::puts(std::string(std::string(g).size(), '=').c_str());
            std::puts("");
            std::puts("=== ================ ======================= =================== ==========");
            std::puts("id  symbol           name                    range               default");
            std::puts("=== ================ ======================= =================== ==========");
        }
        const ParamDef& d = kParams[i];
        std::string range;
        if (d.kind == Kind::Bool) range = "off / on";
        else if (d.kind == Kind::Enum) { range = "choice"; enums.push_back(i); }
        else range = num(d.min) + " .. " + num(d.max) + (unitName(d.unit)[0] ? std::string(" ") + unitName(d.unit) : "");
        std::string def = d.kind == Kind::Bool ? (d.def > 0.5f ? "on" : "off")
                          : (d.kind == Kind::Enum ? d.labels[static_cast<int>(d.def)] : num(d.def));
        std::printf("%-3u %-16s %-23s %-19s %s\n", i, d.symbol, d.name, range.c_str(), def.c_str());
        const bool last = i + 1 == kParamCount || std::string(group(i + 1)) != cur;
        if (last) std::puts("=== ================ ======================= =================== ==========");
    }

    std::puts("");
    std::puts("Choices");
    std::puts("=======");
    std::puts("");
    for (uint32_t i : enums) {
        const ParamDef& d = kParams[i];
        std::printf("``%s``\n", d.symbol);
        // wrap at 79 columns
        std::puts("");
        {
            std::string text; for (int k = 0; k <= static_cast<int>(d.max - d.min); ++k) text += std::to_string(k) + "=" + d.labels[k] + (k < static_cast<int>(d.max - d.min) ? "  " : "");
            std::string l = "  "; size_t pos = 0;
            while (pos < text.size()) {
                size_t sp = text.find("  ", pos); if (sp == std::string::npos) sp = text.size();
                const std::string w = text.substr(pos, sp - pos);
                if (l.size() + w.size() + 2 > 78 && l.size() > 2) { emit(l); l = "  "; }
                l += w + "  ";
                pos = sp + 2;
            }
            if (l.size() > 2) emit(l);
        }
        std::puts("");
    }

    std::puts("Hover help");
    std::puts("==========");
    std::puts("");
    std::puts("The text shown by the editor's TIPS tooltips, per parameter:");
    std::puts("");
    for (uint32_t i = 0; i < kNumInputParams; ++i) {
        const ParamDef& d = kParams[i];
        if (!d.tip || !*d.tip) continue;
        std::printf("``%s``\n", d.symbol);
        // wrap tip at 70 columns, indented
        std::string t = d.tip, l = "    "; size_t pos = 0;
        while (pos < t.size()) {
            size_t sp = t.find(' ', pos); if (sp == std::string::npos) sp = t.size();
            const std::string w = t.substr(pos, sp - pos);
            if (l.size() + w.size() > 76 && l.size() > 4) { emit(l); l = "    "; }
            l += w + " ";
            pos = sp + 1;
        }
        emit(l);
    }
    return 0;
}
